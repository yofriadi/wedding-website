//
// Snapshot: fetched 2026-08-27 from https://router.project-osrm.org
//   GET /route/v1/driving/{lng,lat};110.8053926,-7.5682749
//       ?overview=full&geometries=geojson   (HTTPS; demo server)
// Raw point counts at snapshot time: 79 Tirtonadi / 72 Purwosari /
// 130 Solo Balapan / 345 Adi Soemarmo (before the endpoint fixups below).
//
// This module is deliberately separate from VenueMap.astro: ~630 coordinate
// pairs are 12-18 KB, and the component's bundled script + HTML ship to every
// homepage visitor. It is `await import()`-ed inside the IntersectionObserver
// lazy branch so only scrollers pay for it — this is what keeps the spec's
// "no map resources loaded on initial page load" scenario honest.
//
// Coordinate order: Leaflet [lat, lng] (converted from OSRM's GeoJSON
// [lng, lat] at bake time — raw OSRM order into `new Polyline(...)` renders
// every route ~110 deg off in the ocean).
//
// Endpoint fixups: OSRM snaps BOTH endpoints to the nearest routable road
// point, never the exact pins (the destination snaps ~10 m off to
// [110.805441, -7.568194]; the Adi Soemarmo origin snaps 422.8 m away to
// "Jalan Padang Golf" because the terminal access roads are not in OSM's
// drivable network). Each array therefore has the exact origin marker pin
// PREPENDED as its first point and the exact venue pin (VENUE_LAT/VENUE_LNG
// from ../lib/venue) APPENDED as its final point, so every polyline visually
// connects pin -> pin (spec: "Route endpoints are the exact pins").
//
// Visual note: the prepended Adi Soemarmo stub is a straight ~422 m chord
// from the terminal pin across the apron to the access road. VenueMap.astro
// renders that route's first segment with a dashed dashArray so it reads as
// an access-road connector, not road geometry.

